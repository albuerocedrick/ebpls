/**
 * Rebuild migration 044 from the committed BetterGov / NAMRIA boundary file.
 * Coordinates are derived polygon centroids, NOT surveyed official points.
 * Poblacion -> Zone 1 is supported by the approved specification; every other
 * barangay starts in Zone 3 pending LGU review of road/market classifications.
 * Run only before deploying 044: node scripts/generate-location-zones-migration.js
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const boundaryPath = path.join(root, 'ebpls-server/src/data/liliw-barangays.geojson');

function ringCentroid(ring) {
  // Translate to a local origin to avoid cancellation with small polygons.
  const [ox, oy] = ring[0];
  let twiceArea = 0, x = 0, y = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const ax = ring[i][0] - ox, ay = ring[i][1] - oy;
    const bx = ring[i + 1][0] - ox, by = ring[i + 1][1] - oy;
    const cross = ax * by - bx * ay;
    twiceArea += cross;
    x += (ax + bx) * cross;
    y += (ay + by) * cross;
  }
  if (Math.abs(twiceArea) < 1e-15) throw new Error('Degenerate boundary ring');
  return { area: Math.abs(twiceArea / 2), x: ox + x / (3 * twiceArea), y: oy + y / (3 * twiceArea) };
}

function insideRing([x, y], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function insidePolygon(point, rings) {
  return insideRing(point, rings[0]) && !rings.slice(1).some(ring => insideRing(point, ring));
}

function centroid(geometry) {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  if (!['Polygon', 'MultiPolygon'].includes(geometry.type)) throw new Error('Unsupported boundary geometry');
  let area = 0, x = 0, y = 0;
  for (const rings of polygons) {
    rings.forEach((ring, index) => {
      const c = ringCentroid(ring);
      const weight = index === 0 ? c.area : -c.area;
      area += weight;
      x += c.x * weight;
      y += c.y * weight;
    });
  }
  if (area <= 0) throw new Error('Invalid polygon area');
  const point = [Number((x / area).toFixed(7)), Number((y / area).toFixed(7))];
  // Do not silently seed an out-of-bound centroid for a concave polygon.
  if (!polygons.some(rings => insidePolygon(point, rings))) throw new Error('Centroid is outside its barangay; supply a reviewed representative point');
  return point;
}

function generateMigration() {
  const boundaries = JSON.parse(fs.readFileSync(boundaryPath, 'utf8'));
  if (boundaries.features.length !== 33) throw new Error('Expected 33 Liliw barangays');
  const names = new Set();
  const rows = boundaries.features.map(feature => {
    const name = feature.properties.name;
    if (names.has(name)) throw new Error(`Duplicate barangay: ${name}`);
    names.add(name);
    const [lng, lat] = centroid(feature.geometry);
    const zone = name.includes('(Poblacion)') ? 'Zone 1 (Prime Commercial)' : 'Zone 3 (Rural)';
    return `    ('${name.replaceAll("'", "''")}', ${lat.toFixed(7)}, ${lng.toFixed(7)}, '${zone}')`;
  });
  const sql = `-- Generated by scripts/generate-location-zones-migration.js.
-- Source: committed BetterGov / NAMRIA 2023 barangay polygons.
-- Coordinates are derived area centroids, not official surveyed coordinates.
-- STARTER ZONING: Poblacion = Zone 1; all others = Zone 3 pending LGU review.
-- Zone 2 must be assigned to confirmed highway/main-road barangays by Admin.
BEGIN;

CREATE TABLE public.location_zones (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    foot_traffic_level VARCHAR(10) NOT NULL CHECK (foot_traffic_level IN ('High', 'Medium', 'Low')),
    min_capital_floor NUMERIC(12,2) NOT NULL CHECK (min_capital_floor >= 0),
    fee_multiplier NUMERIC(7,4) NOT NULL CHECK (fee_multiplier > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE public.location_zones ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Authenticated read location zones" ON public.location_zones
    FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin manages location zones" ON public.location_zones
    FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());
GRANT SELECT ON public.location_zones TO authenticated;
GRANT ALL ON public.location_zones TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.location_zones_id_seq TO authenticated, service_role;
GRANT INSERT, UPDATE, DELETE ON public.location_zones TO authenticated;

INSERT INTO public.location_zones (name, foot_traffic_level, min_capital_floor, fee_multiplier) VALUES
    ('Zone 1 (Prime Commercial)', 'High', 50000.00, 1.25),
    ('Zone 2 (Sub-Commercial)', 'Medium', 25000.00, 1.00),
    ('Zone 3 (Rural)', 'Low', 10000.00, 0.80);

ALTER TABLE public.barangays
    ADD COLUMN zone_id INTEGER REFERENCES public.location_zones(id) ON DELETE RESTRICT,
    ADD COLUMN latitude NUMERIC(10,7) CHECK (latitude BETWEEN -90 AND 90),
    ADD COLUMN longitude NUMERIC(10,7) CHECK (longitude BETWEEN -180 AND 180);
CREATE INDEX barangays_zone_id_idx ON public.barangays(zone_id);

WITH seed(name, latitude, longitude, zone_name) AS (VALUES
${rows.join(',\n')}
)
UPDATE public.barangays b
SET latitude = seed.latitude, longitude = seed.longitude, zone_id = z.id
FROM seed JOIN public.location_zones z ON z.name = seed.zone_name
WHERE b.name = seed.name;

-- Abort instead of leaving an incomplete mapping or changing existing IDs.
DO $$
BEGIN
    IF (SELECT count(*) FROM public.barangays WHERE zone_id IS NOT NULL AND latitude IS NOT NULL AND longitude IS NOT NULL) <> 33 THEN
        RAISE EXCEPTION 'Expected 33 matching barangays from migration 030; review lookup names before applying 044';
    END IF;
END $$;

ALTER TABLE public.barangays
    ALTER COLUMN zone_id SET NOT NULL,
    ALTER COLUMN latitude SET NOT NULL,
    ALTER COLUMN longitude SET NOT NULL;

COMMENT ON TABLE public.location_zones IS 'Configurable foot-traffic fee zones. Starter barangay assignments require LGU confirmation before fee assessment rollout.';
COMMENT ON COLUMN public.barangays.latitude IS 'Derived from BetterGov / NAMRIA 2023 polygon centroid; editable by Admin. Not a surveyed official point.';
COMMENT ON COLUMN public.barangays.longitude IS 'Derived from BetterGov / NAMRIA 2023 polygon centroid; editable by Admin. Not a surveyed official point.';
COMMENT ON COLUMN public.barangays.zone_id IS 'Starter assignment: Poblacion = Zone 1; others = Zone 3. Admin must confirm road/market zones before fee assessment rollout.';

COMMIT;
`;
  const target = path.join(root, 'ebpls-server/supabase/migrations/044_location_zones_and_centroids.sql');
  fs.writeFileSync(target, sql, 'utf8');
  console.log('Generated migration 044 with 3 zones and 33 in-boundary derived centroids.');
}

if (require.main === module) generateMigration();
module.exports = { centroid, insidePolygon, generateMigration };
