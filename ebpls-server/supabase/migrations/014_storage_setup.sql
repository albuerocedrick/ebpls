-- 1. Create the private 'documents' bucket.
-- Public = false means files are not accessible via public URL.
-- They require a pre-signed URL generated by the server.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'documents', 
    'documents', 
    false, 
    10485760, -- 10MB limit
    '{image/jpeg, image/png, application/pdf}' -- Strictly allow only these types
)
ON CONFLICT (id) DO NOTHING;

-- 2. Policy: Applicants can upload to their own folder.
-- Folder name MUST match their taxpayer_id.
CREATE POLICY "Applicants can upload to their own folder"
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'documents' AND
    (storage.foldername(name))[1] = (
        SELECT taxpayer_id::text 
        FROM public.taxpayers 
        WHERE user_id = auth.uid()
    )
);

-- 4. Policy: Applicants can read their own documents.
CREATE POLICY "Applicants can view own documents"
ON storage.objects FOR SELECT
TO authenticated
USING (
    bucket_id = 'documents' AND
    (storage.foldername(name))[1] = (
        SELECT taxpayer_id::text 
        FROM public.taxpayers 
        WHERE user_id = auth.uid()
    )
);

-- 5. Policy: Staff (BPLO, Treasury, etc.) can view all documents for verification.
CREATE POLICY "Staff can view all documents"
ON storage.objects FOR SELECT
TO authenticated
USING (
    bucket_id = 'documents' AND
    public.is_staff()
);

-- 6. Policy: No one can UPDATE or DELETE documents once uploaded (for audit integrity).
-- If a user makes a mistake, they should upload a new version.
-- Admins can manually prune if absolutely necessary via service_role.
