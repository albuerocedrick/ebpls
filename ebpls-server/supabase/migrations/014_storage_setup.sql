-- Purpose:   Initialize the private storage bucket for document uploads
--            and define RLS policies for secure file access.
-- Author:    eBPLS Team
-- Policy:    Zero Trust — Files are namespaced by taxpayer_id.
--            Applicants cannot see or overwrite other taxpayers' files.
