-- ---------------------------------------------------------------
-- Custom Type: application_status
-- Encoding the state machine at the type level means Postgres itself
-- rejects any invalid status string before it ever reaches a CHECK constraint.
-- ---------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'application_status') THEN
        CREATE TYPE public.application_status AS ENUM (
            'Draft',
            'Pending',
            'Under Review',
            'Returned',
            'Verified',
            'For Assessment',
            'Assessed',
            'For Payment',
            'Paid',
            'Completed'
        );
    END IF;
END$$;

COMMENT ON TYPE public.application_status IS
    'Canonical state machine enum for business permit applications. '
    'Order follows: Draft→Pending→Under Review→Verified→For Assessment→Assessed→For Payment→Paid→Completed. '
    'Returned is a reversible state that can revert to Pending on resubmission.';

-- ---------------------------------------------------------------
-- Table: applications
-- The central entity for the entire eBPLS workflow.
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.applications (
    -- Government-issued reference number, formatted at the API layer.
    -- Format: APP-{YEAR}-{5-digit sequence}, e.g. APP-2026-00001
    application_no  VARCHAR(20)             PRIMARY KEY,

    business_id     UUID                    NOT NULL REFERENCES public.businesses (business_id) ON DELETE RESTRICT,
    type_id         INTEGER                 NOT NULL REFERENCES public.application_types (id),
    payment_mode_id INTEGER                 REFERENCES public.payment_modes (id),

    -- State machine status — backed by the strongly-typed enum above
    status          public.application_status NOT NULL DEFAULT 'Draft',

    -- Tracks who last changed the status (for audit trail supplement)
    last_updated_by UUID                    REFERENCES public.users (user_id) ON DELETE SET NULL,

    -- Remarks attached by BPLO when returning an application
    -- Required when status transitions to 'Returned'
    return_remarks  TEXT,

    submitted_at    TIMESTAMPTZ,            -- Set when status transitions from Draft → Pending
    created_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE  public.applications                   IS 'Core application entity. Drives the entire eBPLS permit workflow state machine.';
COMMENT ON COLUMN public.applications.application_no   IS 'Human-readable government reference. Format: APP-{YEAR}-{NNNNN}. Generated by application service.';
COMMENT ON COLUMN public.applications.status           IS 'Strongly-typed state machine enum. Transitions validated at API layer; type prevents invalid values at DB layer.';
COMMENT ON COLUMN public.applications.return_remarks   IS 'Mandatory when BPLO returns an application. Must be non-empty for Returned transition.';
COMMENT ON COLUMN public.applications.submitted_at     IS 'Timestamp of final UAF submission (Draft→Pending). Null while still in Draft.';

CREATE OR REPLACE TRIGGER applications_set_updated_at
    BEFORE UPDATE ON public.applications
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------
-- Table: application_drafts
-- Stores the intermediate, step-by-step UAF form state for autosave.
-- One draft per taxpayer (not per business) — they may not have
-- chosen/created their business entity yet when they start the form.
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.application_drafts (
    draft_id     UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    taxpayer_id  UUID        NOT NULL UNIQUE REFERENCES public.taxpayers (taxpayer_id) ON DELETE CASCADE,

    -- Current wizard step the applicant was on (1–5)
    current_step INTEGER     NOT NULL DEFAULT 1 CHECK (current_step BETWEEN 1 AND 5),

    -- The entire form state as a flexible JSONB blob.
    -- This is intentionally JSONB (not a normalized table) because:
    -- (a) Draft data is transient and exploratory — schema may evolve per UAF step.
    -- (b) On final submission, this blob is validated and decomposed into
    --     normalized rows (businesses, applications, etc.) by the API service.
    form_data    JSONB       NOT NULL DEFAULT '{}',

    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE  public.application_drafts             IS 'Transient autosave store for in-progress UAF wizard. One draft per taxpayer at a time.';
COMMENT ON COLUMN public.application_drafts.taxpayer_id IS 'UNIQUE FK — only one in-progress draft per taxpayer allowed simultaneously.';
COMMENT ON COLUMN public.application_drafts.current_step IS 'Last active UAF step (1–5). Used to restore wizard position on resume.';
COMMENT ON COLUMN public.application_drafts.form_data   IS 'Flexible JSONB blob for transient draft state. Decomposed into normalized tables on final submission.';

CREATE OR REPLACE TRIGGER application_drafts_set_updated_at
    BEFORE UPDATE ON public.application_drafts
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();
